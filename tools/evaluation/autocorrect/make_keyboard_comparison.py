#!/usr/bin/env python3
"""Held-out cases for typing through Glyph, Apple's keyboard and Gboard on a phone ->
keyboardUITests/KeyboardComparisonCases.swift (keyboardUITests.testCompareKeyboards).

1 Nov 2026. Each case's context is placed in the field by the test app (every keyboard reads it
from the document) and only the word is typed, with key-centre taps: every keyboard sees the same
letters, so this compares correction, not touch handling. Ten cases per bucket, with and without
context where the corpus has it: ECPS misspellings, synthetic typos, severe (3+ edits: ECPS and
synthetic with context, Birkbeck and Wikipedia without), Birkbeck within 2 edits, real-word errors,
correct words, rare dictionary words and unknown names. The last three must stay as typed.
"""
import hashlib, json, pathlib, random, re
HERE = pathlib.Path(__file__).resolve().parent
PER_BUCKET = 10


def osa(a, b):
    d = [[0] * (len(b) + 1) for _ in range(len(a) + 1)]
    for i in range(len(a) + 1): d[i][0] = i
    for j in range(len(b) + 1): d[0][j] = j
    for i in range(1, len(a) + 1):
        for j in range(1, len(b) + 1):
            d[i][j] = min(d[i - 1][j] + 1, d[i][j - 1] + 1, d[i - 1][j - 1] + (a[i - 1] != b[j - 1]))
            if i > 1 and j > 1 and a[i - 1] == b[j - 2] and a[i - 2] == b[j - 1]: d[i][j] = min(d[i][j], d[i - 2][j - 2] + 1)
    return d[-1][-1]


def main():
    meta = json.loads((HERE/'corpus/cases-meta.json').read_text())
    for extra in ('ext-cases-meta.json', 'keep-cases-meta.json'): meta.update(json.loads((HERE/'corpus'/extra).read_text()))
    context = {}
    for name in ('cases.tsv', 'ext-cases.tsv', 'keep-cases.tsv'):
        for line in open(HERE/'corpus'/name):
            parts = line.rstrip('\n').split('\t')
            if len(parts) >= 5: context[parts[0]] = parts[2]
    half = lambda m: 'tune' if int(hashlib.sha1(m.get('key', m['target']).encode()).hexdigest(), 16) % 2 == 0 else 'held'
    usable = lambda i, m: (half(m) == 'held' and re.fullmatch(r'[A-Za-z]{2,12}', m['typed'])
                           and re.fullmatch(r'[a-z]{2,14}', m['target']) and re.fullmatch(r"[A-Za-z ,.!?']*", context.get(i, '')))
    far = lambda m: osa(m['typed'].lower(), m['target']) >= 3
    buckets = [
        ('misspelling+ctx', lambda i, m: m['set'] == 'ecps' and context[i] and not far(m)),
        ('misspelling', lambda i, m: m['set'] == 'ecps' and not context[i] and not far(m)),
        ('typo+ctx', lambda i, m: m['set'] == 'syn' and context[i] and not far(m)),
        ('typo', lambda i, m: m['set'] == 'syn' and not context[i] and not far(m)),
        ('severe+ctx', lambda i, m: m['set'] in ('ecps', 'syn') and context[i] and far(m)),
        ('severe', lambda i, m: m['set'] in ('ext_birkbeck', 'ext_wikipedia') and far(m)),
        ('birkbeck', lambda i, m: m['set'] == 'ext_birkbeck' and not far(m)),
        ('realword+ctx', lambda i, m: m['set'] == 'realword' and context[i]),
        ('realword', lambda i, m: m['set'] == 'realword' and not context[i]),
        ('correct+ctx', lambda i, m: m['set'] == 'ecps_ok' and context[i]),
        ('correct', lambda i, m: m['set'] == 'ecps_ok' and not context[i]),
        ('rare', lambda i, m: m['set'] == 'keep_word'),
        ('name+ctx', lambda i, m: m['set'] == 'keep_name_ctx'),
        ('name', lambda i, m: m['set'] == 'keep_name'),
    ]
    random.seed(20261101)
    cases, seen = [], set()
    ids = sorted(meta)
    for kind, wanted in buckets:
        pool = [i for i in ids if i in context and usable(i, meta[i]) and wanted(i, meta[i])]
        random.shuffle(pool)
        taken = 0
        for i in pool:
            m = meta[i]
            key = (context[i].lower(), m['typed'].lower(), m['target'])
            if key in seen: continue
            seen.add(key); cases.append((kind, context[i], m['typed'].lower(), m['target'])); taken += 1
            if taken == PER_BUCKET: break
    quote = lambda t: t.replace('\\', '\\\\').replace('"', '\\"')
    body = ',\n'.join(f'\t("{k}", "{quote(c)}", "{t}", "{g}")' for k, c, t, g in cases)
    (HERE.parents[2]/'keyboardUITests/KeyboardComparisonCases.swift').write_text(
        '// Generated by tools/evaluation/autocorrect/make_keyboard_comparison.py: held-out cases; the\n'
        '// test app places the context, the word is typed through each keyboard\n'
        '// (keyboardUITests.testCompareKeyboards). correct, rare and name rows must stay as typed.\n'
        'let keyboardComparisonCases: [(kind: String, context: String, typed: String, intended: String)] = [\n'
        + body + ',\n]\n')
    print(len(cases), 'cases')


if __name__ == '__main__':
    main()
